/**
 * 진행률(0~100) — 화면의 막대가 쓰는 유일한 계산.
 *
 * ── 왜 함수로 빼는가 ─────────────────────────────────────────────────────
 * 화면마다 `Math.round((a / b) * 100)` 을 다시 적으면, 그때마다 같은 두 함정을
 * 다시 밟는다. 둘 다 실제로 밟았다.
 *
 *  · **분모가 0.** 서버가 목표치를 빼먹으면 매퍼가 0 을 넣는다. 0/0 = NaN 이라
 *    `width: "NaN%"` 라는 스타일이 나가고, 분자가 조금이라도 있으면 Infinity →
 *    100% 가 되어 **달성한 것처럼** 보인다. 목표가 없는 날의 '목표 달성'은
 *    거짓말이다.
 *  · **음수.** 뺄셈으로 만드는 진행률(예: 다음 레벨까지 남은 장수)은 서버가 앱과
 *    다른 단위를 쓰는 순간 음수가 된다. `Math.min(100, …)` 은 위만 막으므로
 *    `width: "-50%"` 가 그대로 나간다 — 웹에서는 무시되고, 네이티브에서는
 *    막대가 엉뚱하게 그려진다.
 *
 * 그래서 답은 늘 0~100 사이의 정수이고, 계산할 수 없으면 0 이다. 0 은 '아직
 * 아무것도 안 했다'로 읽히므로, 모르는 것을 채워 보여주는 쪽보다 정직하다.
 */
export function percent(part: number, whole: number): number {
  if (!Number.isFinite(part) || !Number.isFinite(whole) || whole <= 0) return 0;
  return Math.min(100, Math.max(0, Math.round((part / whole) * 100)));
}
