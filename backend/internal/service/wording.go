package service

import "fmt"

// 화면에 나가는 말.
//
// ── 이 파일의 존재 이유 ────────────────────────────────────────────────────
// 이 진단을 실제로 쓰는 사람은 데이터 분석가가 아니라 **교육 담당자**다.
// 분석 쪽에서 자연스러운 말이 그 사람에게는 벽이 된다:
//
//	'또래'      → 같은 팀인가? 같은 나이인가? (실제로는 '같은 문제를 푼 다른 직원')
//	'실패율'    → 시험에 떨어진 비율처럼 읽힌다
//	'숙달률'    → 무엇을 기준으로 숙달인지 알 수 없다
//	'%p'        → 퍼센트포인트를 아는 사람은 많지 않다. 58%p 를 58% 로 읽으면
//	              "절반 넘게 틀린다"가 "절반만큼 더 틀린다"로 바뀐다 — 뜻이 달라진다
//	'표본'      → 통계 용어
//
// 말을 쉽게 바꾼다고 내용이 묽어지지는 않는다. 숫자도 비교 대상도 그대로 두고
// **부르는 이름만** 바꾼다. 뜻이 흐려지는 쪽으로는 바꾸지 않는다.
//
// 한 곳에 모아 두는 이유: 같은 개념을 파일마다 다르게 부르면 읽는 사람은
// 그것이 서로 다른 지표라고 생각한다. 그게 용어가 어려운 것보다 나쁘다.
const (
	// peerWord 는 비교 대상. '또래'는 같은 나이·같은 팀으로 오해된다.
	peerWord = "다른 직원"
	// peerLongWord 는 처음 나올 때 쓰는 완전한 표현.
	peerLongWord = "같은 문제를 푼 다른 직원"
	// missWord 는 실패율. '틀린 비율'이 하는 일을 그대로 말한다.
	missWord = "틀린 비율"
	// masteryWord 는 숙달률. 기준(상자 4 이상)을 말로 풀면 길어지므로
	// '확실히 익힌'까지만 말하고, 정확한 기준은 근거의 Rule 에서 밝힌다.
	masteryWord = "확실히 익힌 비율"
	// sampleWord 는 표본.
	sampleWord = "비교에 쓴 기록"
)

// pctText 는 비율을 화면과 같은 규칙(정수 %)으로 문자열화한다.
// 서버와 화면이 각자 반올림하면 근거 문장과 표의 숫자가 1% 어긋난다.
func pctText(v float64) string {
	return fmt.Sprintf("%.0f%%", v*100)
}

// gapText 는 두 비율의 차이를 사람이 읽는 말로 옮긴다.
//
// '+58%p' 라고 쓰지 않는다. 퍼센트포인트를 모르는 사람은 그것을 58% 로 읽고,
// 그러면 "절반 넘게 더 틀린다"가 "절반만큼 더 틀린다"로 바뀐다 — 완전히 다른 말이다.
// '58%포인트 더'라고 쓰면 적어도 % 와 다른 것임은 보이고, 앞뒤 문장이 뜻을 채운다.
func gapText(gap float64) string {
	p := gap * 100
	if p >= 0 {
		return fmt.Sprintf("%.0f%%포인트 더", p)
	}
	return fmt.Sprintf("%.0f%%포인트 적게", -p)
}

// timesText 는 '몇 배'로 말한다.
//
// 차이를 말하는 방법이 하나뿐이면 감이 안 오는 사람이 생긴다. 17% 와 75% 는
// '58%포인트 더'이기도 하고 '4배 넘게'이기도 한데, 뒤엣것이 훨씬 빨리 와닿는다.
// 기준이 0 이거나 배수가 무의미하게 크면 빈 문자열을 준다 — 억지로 만든 비유는
// 없느니만 못하다.
func timesText(mine, base float64) string {
	if base <= 0 || mine <= 0 || mine <= base {
		return ""
	}
	ratio := mine / base
	if ratio < 1.5 || ratio > 20 {
		return ""
	}
	return fmt.Sprintf("%.1f배", ratio)
}
